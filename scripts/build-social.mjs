/**
 * Everything that gets posted: the avatar, five cards, and the video frames.
 *
 *   node scripts/build-social.mjs        # writes the HTML
 *   node scripts/render-social.mjs       # drives Chrome and ffmpeg over it
 *
 * ## Why they are generated
 *
 * Every figure on every card is read from `dist/data/index.json` at build time.
 * Nothing here is typed by hand, so a card cannot claim 441 incidents on a day
 * the ledger holds 460 — which is the ordinary way marketing material starts
 * lying about a product without anybody deciding to.
 *
 * It also means the whole set is regenerated by running this again after a
 * pulse, rather than being five files somebody has to remember to redo.
 *
 * ## The series
 *
 * One template, five posts, so the account reads as one voice rather than five
 * unrelated graphics. Each card is a single measured claim: an eyebrow saying
 * which reading it came from, the figure, one sentence, and the domain. No
 * adjectives — the argument is that these numbers can be checked, and a card
 * that opens with "powerful" contradicts it on the first line.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

const bundle = JSON.parse(readFileSync(`${ROOT}dist/data/index.json`, 'utf8'));
const mark = readFileSync(`${ROOT}assets/brand/mark-dark.svg`, 'utf8');

const n = (value) => value.toLocaleString('en');

/** Shared head: the site's own fonts and tokens, so the account cannot drift from the product. */
const HEAD = `<meta charset="utf-8">
<style>
  @font-face { font-family: 'Plex Condensed'; font-weight: 600;
    src: url('../../dist/fonts/ibm-plex-sans-condensed-latin-600-normal.woff2') format('woff2'); }
  @font-face { font-family: 'Plex Mono'; font-weight: 400;
    src: url('../../dist/fonts/ibm-plex-mono-latin-400-normal.woff2') format('woff2'); }
  @font-face { font-family: 'Plex Serif'; font-weight: 400;
    src: url('../../dist/fonts/ibm-plex-serif-latin-400-normal.woff2') format('woff2'); }

  * { margin: 0; padding: 0; box-sizing: border-box; }
  body { background: #121212; color: #e8e8e8; font-family: 'Plex Mono', monospace; overflow: hidden; }

  .eyebrow {
    font-family: 'Plex Condensed', sans-serif; font-weight: 600;
    font-size: 19px; letter-spacing: 0.2em; text-transform: uppercase; color: #9e9e9e;
  }
  /* Tabular figures, always. A column of numbers that shifts as it counts is a
     number nobody trusts, and this is the only thing on the card that matters. */
  .figure {
    font-family: 'Plex Condensed', sans-serif; font-weight: 600;
    font-variant-numeric: tabular-nums; font-size: 168px; line-height: 0.9;
    color: #d2e2f4; letter-spacing: -0.02em;
  }
  .say { font-family: 'Plex Serif', Georgia, serif; font-size: 33px; line-height: 1.45; color: #cfcfcf; }
  .foot {
    position: absolute; left: 76px; right: 76px; bottom: 52px;
    display: flex; justify-content: space-between; align-items: center;
    font-family: 'Plex Condensed', sans-serif; font-weight: 600;
    font-size: 17px; letter-spacing: 0.18em; text-transform: uppercase; color: #6b6b6b;
  }
  .foot .mark { display: flex; align-items: center; gap: 14px; color: #9e9e9e; }
</style>`;

/** 1200x675. The 16:9 that X shows uncropped in a timeline. */
function card({ eyebrow, figure, unit, say }) {
  return `<!doctype html><html lang="en"><head>${HEAD}
<style>
  body { width: 1200px; height: 675px; position: relative; }
  .frame { position: absolute; inset: 0; padding: 74px 76px 0; display: flex;
           flex-direction: column; justify-content: center; gap: 26px; padding-bottom: 130px; }
  .unit { font-family: 'Plex Condensed', sans-serif; font-weight: 600; font-size: 27px;
          letter-spacing: 0.13em; text-transform: uppercase; color: #9e9e9e; margin-top: 4px; }
  .say { max-width: 30ch; }
</style></head>
<body>
  <div class="frame">
    <span class="eyebrow">${eyebrow}</span>
    <div>
      <div class="figure">${figure}</div>
      <div class="unit">${unit}</div>
    </div>
    <p class="say">${say}</p>
  </div>
  <div class="foot">
    <span class="mark">${mark.replace('width="64" height="64"', 'width="30" height="30"')} Sighttrue</span>
    <span>sighttrue.com</span>
  </div>
</body></html>`;
}

