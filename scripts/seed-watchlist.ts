const BY_CATEGORY: Record<Category, readonly string[]> = {
  'ai-ml': AI_ML,
  'web-framework': WEB_FRAMEWORK,
  database: DATABASE,
  devtool: DEVTOOL,
  'crypto-web3': CRYPTO_WEB3,
};

function build(): WatchlistEntry[] {
  const entries: WatchlistEntry[] = [];
  const seen = new Map<string, Category>();

  for (const [category, repos] of Object.entries(BY_CATEGORY) as [
    Category,
    readonly string[],
  ][]) {
    for (const id of repos) {
      if (!/^[\w.-]+\/[\w.-]+$/.test(id)) {
        throw new Error(`seed-watchlist: "${id}" is not a valid owner/repo`);
      }

      const key = id.toLowerCase();
      const existing = seen.get(key);
      if (existing) {
        throw new Error(
          `seed-watchlist: "${id}" appears in both ${existing} and ${category}`,
        );
      }
      seen.set(key, category);

      entries.push({ id, category, added: ADDED, active: true });
    }
  }

  return entries;
}

function main(): void {
  const force = process.argv.includes('--force');

  if (existsSync(WATCHLIST_PATH) && !force) {
    console.error(
      'watchlist.jsonl already exists. It is the source of truth once seeded —\n' +
        'edit it directly and commit the change with a reason. Pass --force only\n' +
        'to rebuild from scratch.',
    );
    process.exitCode = 1;
    return;
  }

  const entries = build();
  writeWatchlist(entries);

  const counts = new Map<Category, number>();
  for (const entry of entries) {
    counts.set(entry.category, (counts.get(entry.category) ?? 0) + 1);
  }

  console.log(`wrote ${entries.length} entries to data/watchlist.jsonl`);
  for (const [category, count] of [...counts].sort()) {
    console.log(`  ${category.padEnd(14)} ${String(count).padStart(3)}`);
  }
}

main();
