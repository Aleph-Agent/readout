/**
 * One-time bootstrap for `data/watchlist.jsonl`.
 *
 * After this runs, the JSONL file is the source of truth. The watchlist is a
 * committed file, not something generated at runtime, and every change to it is
 * a reviewed commit — the set of repositories being watched is an editorial
 * claim, not configuration. This script therefore refuses to clobber an
 * existing file unless explicitly forced.
 *
 *   node scripts/seed-watchlist.ts
 *   node scripts/seed-watchlist.ts --force
 *
 * The starting set is ~400 repositories across five categories. The budget
 * supports several thousand, so growth from here is an editorial decision
 * rather than a technical one.
 *
 * Names are recorded as GitHub spells them. Any that have since been renamed
 * will answer 404 or redirect on the first real collector run; the collector
 * marks those inactive and continues rather than crashing. Validating them is
 * Prompt 2's job — this script makes no network calls.
 */

