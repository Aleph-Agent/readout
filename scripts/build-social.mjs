/**
 * The video, as one page that draws any frame it is asked for.
 *
 * `?f=N` rather than a CSS animation left to run. A screenshot of a playing
 * animation lands wherever the renderer happened to be, so the same command
 * twice gives two different films. Every value here is computed from the frame
 * number, which makes the whole thing reproducible and lets a bad second be
 * re-rendered on its own.
 */
const FPS = 30;
const SECONDS = 8;

const film = `<!doctype html><html lang="en"><head>${HEAD}
<style>
  body { width: 1200px; height: 675px; position: relative; }
  .stage { position: absolute; inset: 0; display: grid; place-items: center; }
  .lockup { display: flex; align-items: center; gap: 30px; }
  .word { font-family: 'Plex Condensed', sans-serif; font-weight: 600; font-size: 92px;
          letter-spacing: -0.015em; line-height: 1; }
  .line { font-family: 'Plex Serif', Georgia, serif; font-size: 34px; color: #cfcfcf;
          text-align: center; max-width: 26ch; }
  .rows { display: grid; gap: 22px; width: 660px; }
  .row { display: flex; justify-content: space-between; align-items: baseline;
         border-bottom: 1px solid #2c2c2c; padding-bottom: 12px; }
  .row span { font-family: 'Plex Condensed', sans-serif; font-weight: 600; font-size: 21px;
              letter-spacing: 0.14em; text-transform: uppercase; color: #9e9e9e; }
  .row b { font-weight: 400; font-size: 46px; font-variant-numeric: tabular-nums; color: #d2e2f4; }
  .url { font-family: 'Plex Condensed', sans-serif; font-weight: 600; font-size: 30px;
         letter-spacing: 0.2em; text-transform: uppercase; color: #9e9e9e; }
  .col { display: grid; gap: 40px; place-items: center; }
</style></head>
<body>
  <div class="stage" id="stage"></div>
<script>
  const FPS = ${FPS};
  const frame = Number(new URLSearchParams(location.search).get('f') || 0);
  const t = frame / FPS;

  // Ease-out. Motion that decelerates reads as something settling into place;
  // linear motion reads as a slide, which is decoration.
  const ease = (x) => 1 - Math.pow(1 - Math.min(1, Math.max(0, x)), 3);
  const window_ = (from, to) => ease((t - from) / (to - from));

  const FIGURES = ${JSON.stringify([
    ['Repositories', bundle.watchlist.active],
    ['Incidents kept', bundle.incidents.total],
    ['EOL clocks', bundle.lifecycle.dated],
    ['Commit histories', bundle.contributors.measured],
  ])};

  const mark = ${JSON.stringify(mark.replace('width="64" height="64"', 'width="104" height="104"'))};
  const stage = document.getElementById('stage');

  if (t < 2.6) {
    // The name, arriving.
    const p = window_(0.2, 1.4);
    stage.innerHTML =
      '<div class="lockup" style="opacity:' + p + ';transform:translateY(' + (18 - 18 * p) + 'px)">' +
      mark + '<span class="word">Sighttrue</span></div>';
  } else if (t < 5.4) {
    // The figures, counting. Counting rather than appearing, because the claim
    // is that these are measured — and a number that ticks up reads as a
    // reading being taken rather than a badge being placed.
    const p = window_(2.7, 4.6);
    stage.innerHTML = '<div class="rows">' + FIGURES.map((row, i) => {
      const own = ease((t - 2.7 - i * 0.18) / 1.5);
      const value = Math.round(row[1] * own).toLocaleString('en');
      return '<div class="row" style="opacity:' + Math.min(1, own * 1.6) + '">' +
        '<span>' + row[0] + '</span><b>' + value + '</b></div>';
    }).join('') + '</div>';
    stage.style.opacity = String(t > 5.1 ? 1 - (t - 5.1) / 0.3 : 1);
  } else {
    const p = window_(5.5, 6.6);
    stage.innerHTML =
      '<div class="col" style="opacity:' + p + '">' +
      mark +
      '<p class="line">Take the reading, and check it.</p>' +
      '<span class="url">sighttrue.com</span></div>';
  }
</script>
</body></html>`;

writeFileSync(`${ROOT}assets/brand/film.html`, film, 'utf8');

/** The avatar. One mark, nothing else: the only size that matters is 48px. */
writeFileSync(
  `${ROOT}assets/brand/avatar.html`,
  `<!doctype html><meta charset="utf-8">
<style>html,body{margin:0;padding:0}
body{width:400px;height:400px;background:#121212;display:grid;place-items:center}</style>
${mark.replace('width="64" height="64"', 'width="312" height="312"')}`,
  'utf8',
);

console.log(`${CARDS.length} cards, film.html (${SECONDS}s at ${FPS}fps) and avatar.html written`);
console.log(`frames to render: ${SECONDS * FPS}`);
